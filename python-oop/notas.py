#Oque e uma classe em OOP
"Classe e o molde do objeto, onde se declara os atributs é os metodos, caracteristicas do objetos"


#OQUE E O METODO CONTRUTOR __INIT__
"O método __init__ é o constrútor da classe. Ele é chamado"
"automaticamente toda vez que um objeto é criado, e serve para"
"inicializar os atributos desse objeto usando o self"

# ATRIBUTOS DE CLASS
"Atributos da class, sao as caracteristicas formais, de uma class onde o objeto estanciad herda esses atributos"
"Exemplos como nome, idade, ou id, sao referencias de um objeto"

# METODOS OU COMPORTAMENTOS
"Metodos sao funçoes da class onde o objeto estanciado desta classe pode usar, ou chamar"
"Metodos vao definir o tipo de comportamentos que o objeto ter !"
"Metodos sao ensnciais para o polimorfismo"